import assert from 'node:assert/strict';
import { build } from 'esbuild';

const calls = [], pending = [];
globalThis.window = { __TAURI_INTERNALS__: { invoke(command, args) {
  calls.push({ command, args });
  if (command === 'get_tool_control' || command === 'tier_terminal_input' || command === 'tier_terminal_raw_write' || command === 'claude_session_send' || command === 'start_fs_watcher') return new Promise((resolve, reject) => pending.push({ command, args, resolve, reject }));
  return Promise.resolve(null);
} } };
const output = await build({ entryPoints: ['src/tauri.ts'], bundle: true, write: false, platform: 'node', format: 'esm' });
const { invoke } = await import(`data:text/javascript;base64,${Buffer.from(output.outputFiles[0].text).toString('base64')}`);
const flush = () => new Promise(resolve => setImmediate(resolve));
const reads = Array.from({ length: 6 }, () => invoke('get_tool_control', { kind: 'browser' }));
assert.equal(pending.length, 1, 'six simultaneous launches share one capability scan');
pending.shift().resolve('old');
assert.deepEqual(await Promise.all(reads), Array(6).fill('old'));
const fresh = invoke('get_tool_control', { kind: 'browser' });
assert.equal(pending.length, 1, 'settled reads do not hide externally changed configuration');
await invoke('set_tool_control', { kind: 'browser', tool: 'claude', enabled: false });
const afterWrite = invoke('get_tool_control', { kind: 'browser' });
assert.equal(pending.length, 2, 'a configuration write invalidates any earlier in-flight read');
pending.shift().resolve('stale'); pending.shift().reject(new Error('read failed'));
assert.equal(await fresh, 'stale'); await assert.rejects(afterWrite, /read failed/);
const retry = invoke('get_tool_control', { kind: 'browser' }); pending.shift().resolve('current'); assert.equal(await retry, 'current');

const first = invoke('tier_terminal_input', { sessionId: 'a', data: 'one' });
const second = invoke('tier_terminal_raw_write', { sessionId: 'a', data: 'two' });
const other = invoke('tier_terminal_input', { sessionId: 'b', data: 'other' });
await flush();
assert.deepEqual(pending.map(item => item.args.data), ['one', 'other'], 'a blocked pipe cannot block another tab; the same tab stays ordered');
await invoke('tier_terminal_kill', { sessionId: 'a' });
assert.equal(calls.at(-1).command, 'tier_terminal_kill', 'close bypasses the blocked input queue');
pending.shift().resolve(); await first; await flush();
assert.deepEqual(pending.map(item => item.args.data), ['other', 'two']);
pending.shift().resolve(); await other;
pending.shift().reject(new Error('pipe closed')); await assert.rejects(second, /pipe closed/);
const recovered = invoke('tier_terminal_input', { sessionId: 'a', data: 'retry' });
await flush(); pending.shift().resolve(); await recovered;
const prompt = invoke('claude_session_send', { id: 'desktop', generation: 'old', text: 'with images' });
const followUp = invoke('claude_session_send', { id: 'desktop', generation: 'old', text: 'follow up' });
const replacement = invoke('claude_session_send', { id: 'desktop', generation: 'new', text: 'new conversation' });
await flush();
assert.deepEqual(pending.map(item => item.args.text), ['with images', 'new conversation'], 'desktop prompts stay ordered while restarted generations remain independent');
await invoke('claude_session_control', { id: 'desktop', generation: 'old', request: { subtype: 'interrupt' } });
await invoke('claude_session_close', { id: 'desktop', generation: 'old' });
assert.deepEqual(calls.slice(-2).map(item => item.command), ['claude_session_control', 'claude_session_close'], 'interrupt and close bypass queued desktop prompts');
pending.shift().resolve(); await prompt; await flush();
assert.deepEqual(pending.map(item => item.args.text), ['new conversation', 'follow up']);
pending.shift().resolve(); pending.shift().resolve(); await Promise.all([replacement, followUp]);
const beforeWatcher = calls.length;
const oldWatch = invoke('start_fs_watcher', { path: 'old' });
const stopWatch = invoke('stop_fs_watcher');
const newWatch = invoke('start_fs_watcher', { path: 'new' });
assert.equal(calls.length, beforeWatcher + 1, 'watcher transitions queue while an old folder is still starting');
await invoke('list_directory', { path: 'new' });
pending.shift().resolve(); await oldWatch; await flush();
assert.deepEqual(calls.slice(beforeWatcher).map(item => item.command), ['start_fs_watcher', 'list_directory', 'stop_fs_watcher', 'start_fs_watcher']);
assert.equal(pending[0].args.path, 'new');
pending.shift().resolve(); await Promise.all([stopWatch, newWatch]);
console.log('OK: shared concurrent reads, mutation invalidation, failure retry, per-terminal input order and independent close');
